#!/usr/bin/env python3
"""Write indra/newview/app_settings/xui_lookup_names.txt (#1599).

The list holds every control name the viewer code looks up by a string literal:
getChild<T>("name"), findChild<T>("name"), getChildView("name"), childSet*("name", ...),
hasChild("name") and the like, in indra/newview and indra/llui.

The skin importer and the runtime XUI fallback use it to decide which named controls an
imported layout file must keep: the names in our copy of that file that are also on this
list. Names built at run time (string concatenation, loops) are not seen, so the check is
an approximation that errs on the side of accepting a file.

Usage: gen_xui_lookup_names.py [--check]   (--check: exit 1 if the file is out of date)
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "indra", "newview", "app_settings", "xui_lookup_names.txt")
SOURCE_DIRS = ("indra/newview", "indra/llui")
SKIP_DIRS = ("tests", "vkgfx", "vkclean", "third_party")

CALLS = (r"getChild\s*<[^<>()]*(?:<[^<>()]*>[^<>()]*)?>", r"findChild\s*<[^<>()]*(?:<[^<>()]*>[^<>()]*)?>",
         r"getChildRef\s*<[^<>()]*>", r"getChildView", r"findChildView", r"hasChild",
         r"child[A-Z][A-Za-z]*", r"getPanelByName", r"findPanelByName", r"getChildList",
         r"selectTabByName", r"getText\s*<[^<>()]*>")
PATTERN = re.compile(r"(?:%s)\s*\(\s*\"([^\"\\]{1,128})\"" % "|".join(CALLS))
NAME_OK = re.compile(r"^[A-Za-z0-9_.\-]+$")

HEADER = """# Control names the viewer code looks up by name (getChild / findChild / childSet* ...).
# Generated by scripts/ui/gen_xui_lookup_names.py -- do not edit by hand; rerun the script.
# Used by the skin importer and the runtime XUI fallback (#1599): an imported layout file must
# keep every name on this list that our own copy of the file has.
"""


def collect():
    names = set()
    for rel in SOURCE_DIRS:
        base = os.path.join(ROOT, rel)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for fn in sorted(filenames):
                if not fn.endswith((".cpp", ".h")):
                    continue
                with open(os.path.join(dirpath, fn), encoding="utf-8", errors="replace") as f:
                    text = f.read()
                for m in PATTERN.finditer(text):
                    name = m.group(1)
                    if NAME_OK.match(name):
                        names.add(name)
    return names


def render(names):
    return HEADER + "".join(n + "\n" for n in sorted(names))


def main():
    text = render(collect())
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != text:
            print("%s is out of date: run scripts/ui/gen_xui_lookup_names.py" % os.path.relpath(OUT, ROOT))
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d names)" % (os.path.relpath(OUT, ROOT), text.count("\n") - HEADER.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
